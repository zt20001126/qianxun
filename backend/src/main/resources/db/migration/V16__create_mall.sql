CREATE TABLE mall_product (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '商品主键',
    name VARCHAR(120) NOT NULL COMMENT '商品名称',
    description TEXT NOT NULL COMMENT '商品介绍及规格',
    images JSON NOT NULL COMMENT '商品图片地址列表',
    price DECIMAL(12,2) NOT NULL COMMENT '当前商品单价',
    status VARCHAR(20) NOT NULL COMMENT '商品上架状态',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_mall_product_status (status, id),
    CONSTRAINT chk_mall_product_price CHECK (price >= 0),
    CONSTRAINT chk_mall_product_status CHECK (status IN ('ON_SHELF', 'OFF_SHELF'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商城商品';

CREATE TABLE mall_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '商品订单主键',
    order_no VARCHAR(64) NOT NULL COMMENT '商品订单号',
    member_id BIGINT UNSIGNED NOT NULL COMMENT '下单会员',
    product_id BIGINT UNSIGNED NOT NULL COMMENT '商品主键',
    product_name VARCHAR(120) NOT NULL COMMENT '下单时商品名称快照',
    quantity INT UNSIGNED NOT NULL COMMENT '购买数量',
    total_amount DECIMAL(12,2) NOT NULL COMMENT '商品总额',
    paid_amount DECIMAL(12,2) NOT NULL COMMENT '实际支付金额',
    points_used INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '使用积分数量',
    recipient_name VARCHAR(80) NOT NULL COMMENT '收货人姓名快照',
    recipient_phone VARCHAR(20) NOT NULL COMMENT '收货手机号快照',
    shipping_address VARCHAR(500) NOT NULL COMMENT '收货地址快照',
    status VARCHAR(20) NOT NULL COMMENT '商品订单状态',
    express_company VARCHAR(100) NULL COMMENT '快递公司',
    tracking_no VARCHAR(100) NULL COMMENT '快递单号',
    paid_at DATETIME(3) NOT NULL COMMENT '支付成功时间',
    shipped_at DATETIME(3) NULL COMMENT '发货时间',
    completed_at DATETIME(3) NULL COMMENT '完成时间',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_mall_order_no (order_no),
    KEY idx_mall_order_member_status (member_id, status, id),
    KEY idx_mall_order_status (status, id),
    CONSTRAINT fk_mall_order_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_mall_order_product FOREIGN KEY (product_id) REFERENCES mall_product (id),
    CONSTRAINT chk_mall_order_quantity CHECK (quantity > 0),
    CONSTRAINT chk_mall_order_amount CHECK (total_amount >= 0 AND paid_amount >= 0 AND paid_amount <= total_amount),
    CONSTRAINT chk_mall_order_status CHECK (status IN ('PENDING_SHIPMENT', 'SHIPPED', 'COMPLETED', 'REFUNDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商城正式订单';

CREATE TABLE mall_payment (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '支付记录主键',
    payment_no VARCHAR(64) NOT NULL COMMENT '商城支付单号',
    mall_order_id BIGINT UNSIGNED NULL COMMENT '支付成功后创建的订单',
    member_id BIGINT UNSIGNED NOT NULL COMMENT '下单会员',
    product_id BIGINT UNSIGNED NOT NULL COMMENT '商品主键',
    product_name VARCHAR(120) NOT NULL COMMENT '商品名称快照',
    quantity INT UNSIGNED NOT NULL COMMENT '购买数量',
    total_amount DECIMAL(12,2) NOT NULL COMMENT '商品总额快照',
    points_used INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '预占积分数量',
    amount DECIMAL(12,2) NOT NULL COMMENT '积分抵扣后应付金额',
    recipient_name VARCHAR(80) NOT NULL COMMENT '收货人姓名',
    recipient_phone VARCHAR(20) NOT NULL COMMENT '收货手机号',
    shipping_address VARCHAR(500) NOT NULL COMMENT '收货地址',
    payment_method VARCHAR(20) NOT NULL COMMENT '支付方式',
    transaction_id VARCHAR(64) NULL COMMENT '支付渠道交易号',
    wechat_prepay_id VARCHAR(128) NULL COMMENT '微信预支付标识',
    status VARCHAR(20) NOT NULL COMMENT '支付状态',
    expires_at DATETIME(3) NOT NULL COMMENT '支付有效截止时间',
    paid_at DATETIME(3) NULL COMMENT '支付成功时间',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_mall_payment_no (payment_no),
    UNIQUE KEY uk_mall_payment_order (mall_order_id),
    UNIQUE KEY uk_mall_payment_transaction (transaction_id),
    KEY idx_mall_payment_member_status (member_id, status, expires_at),
    KEY idx_mall_payment_status_expiry (status, expires_at),
    CONSTRAINT fk_mall_payment_order FOREIGN KEY (mall_order_id) REFERENCES mall_order (id),
    CONSTRAINT fk_mall_payment_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_mall_payment_product FOREIGN KEY (product_id) REFERENCES mall_product (id),
    CONSTRAINT chk_mall_payment_quantity CHECK (quantity > 0),
    CONSTRAINT chk_mall_payment_amount CHECK (total_amount >= 0 AND amount >= 0 AND amount <= total_amount),
    CONSTRAINT chk_mall_payment_method CHECK (payment_method IN ('MOCK', 'WECHAT')),
    CONSTRAINT chk_mall_payment_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商城支付和待支付快照';

CREATE TABLE mall_refund (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '退款记录主键',
    mall_order_id BIGINT UNSIGNED NOT NULL COMMENT '商品订单主键',
    mall_payment_id BIGINT UNSIGNED NOT NULL COMMENT '商品支付记录主键',
    refund_no VARCHAR(64) NOT NULL COMMENT '商户退款单号',
    wechat_refund_id VARCHAR(64) NULL COMMENT '微信退款单号',
    amount DECIMAL(12,2) NOT NULL COMMENT '整单退款金额',
    status VARCHAR(20) NOT NULL COMMENT '退款状态',
    refunded_at DATETIME(3) NULL COMMENT '渠道确认退款时间',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_mall_refund_no (refund_no),
    UNIQUE KEY uk_mall_refund_wechat_id (wechat_refund_id),
    KEY idx_mall_refund_order (mall_order_id, id),
    CONSTRAINT fk_mall_refund_order FOREIGN KEY (mall_order_id) REFERENCES mall_order (id),
    CONSTRAINT fk_mall_refund_payment FOREIGN KEY (mall_payment_id) REFERENCES mall_payment (id),
    CONSTRAINT chk_mall_refund_amount CHECK (amount >= 0),
    CONSTRAINT chk_mall_refund_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商城退款流水';

